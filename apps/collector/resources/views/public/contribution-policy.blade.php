<h2>1. Qui peut contribuer ?</h2>
<p>Toute personne qui parle le San ou connaît des mots, expressions ou usages peut participer. La création d’un compte est facultative pour répondre au questionnaire.</p>

<h2>2. Ce que nous demandons</h2>
<p>Les contributeurs répondent à des mots ou phrases en français en proposant une forme San par écrit, par audio, ou avec les deux. Lorsqu’une réponse est incertaine, il vaut mieux passer la question plutôt que d’inventer une traduction.</p>

<h2>3. Contexte linguistique</h2>
<p>Nous demandons surtout la localité où la personne a principalement appris ou parlé le San. Nous ne demandons pas au public de maîtriser les étiquettes linguistiques techniques. La variété est ensuite examinée pendant la validation.</p>

<h2>4. Validation humaine</h2>
<p>Une contribution soumise n’est pas automatiquement considérée comme correcte. Elle peut être transcrite, corrigée, validée ou rejetée par des personnes habilitées. La réponse originale est conservée afin de garder une trace de la donnée telle qu’elle a été fournie.</p>

<h2>5. Audio et consentement</h2>
<p>Un enregistrement audio peut servir à la transcription et à la validation. Son utilisation pour l’entraînement de modèles ou sa publication doit respecter la version de consentement acceptée par le contributeur.</p>

<h2>6. Qualité des données</h2>
<p>Les contributions fabriquées, copiées sans droit depuis un dictionnaire, une application ou une autre source, ainsi que les données contenant volontairement de fausses informations, peuvent être rejetées.</p>

<h2>7. Respect des personnes</h2>
<p>Le projet vise à documenter et valoriser la langue sans opposer les communautés ni hiérarchiser leurs usages. Les désaccords linguistiques doivent être traités comme des différences à documenter et à contextualiser.</p>

<h2>8. Réutilisation dans le projet</h2>
<p>Les données validées peuvent être utilisées pour construire progressivement un lexique, un corpus bilingue, des outils de traduction et des ressources d’apprentissage, uniquement dans le cadre permis par le consentement et la licence applicables aux données.</p>
